#!/usr/bin/env python3
"""Encrypt and pack a model blob into the image the loader expects.

The model is cut into tiles of --tile bytes (the last one may be shorter,
padded with zeros to 16 bytes). Each tile becomes one record:

    header (16 B)   tile index, model version, payload length, tile count (u32 LE)
    C               payload, AES-128-CTR under K1
    T (16 B)        AES-128-CMAC under K2 over header || C

CTR counter block of tile i: nonce (8 B) || i (u32 BE) || block number (u32 BE).
Tile index, version and tile count are under the tag, so tiles cannot be
swapped, replayed from an older model, or dropped.

Writes model.enc, model.plain (padded plain model, for checking and for the
no-protection baseline) and image.h (constants and test keys) to --out.

    python3 tools/pack.py build/models/cnn.bin --out build/images/cnn [--tile 4096]
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aes_ref  # noqa: E402

# Test keys. In the real system the security island provisions K1 and K2 at
# secure boot; they never sit next to the image.
K1 = bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c")
K2 = bytes.fromhex("603deb1015ca71be2b73aef0857d7781")
NONCE = bytes.fromhex("a0a1a2a3a4a5a6a7")
VERSION = 3


def c_bytes(b):
    return "{" + ",".join(f"0x{x:02x}" for x in b) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("--out", required=True)
    ap.add_argument("--tile", type=int, default=4096)
    args = ap.parse_args()
    assert args.tile % 16 == 0 and args.tile >= 16
    aes_ref.self_test()

    plain = open(args.model, "rb").read()
    plain += bytes(-len(plain) % 16)
    n_tiles = (len(plain) + args.tile - 1) // args.tile
    enc = bytearray()
    for i in range(n_tiles):
        payload = plain[i * args.tile:(i + 1) * args.tile]
        header = struct.pack("<4I", i, VERSION, len(payload), n_tiles)
        counter = NONCE + struct.pack(">II", i, 0)
        c = aes_ref.ctr(K1, counter, payload)
        enc += header + c + aes_ref.cmac(K2, header + c)

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "model.enc"), "wb") as fh:
        fh.write(enc)
    with open(os.path.join(args.out, "model.plain"), "wb") as fh:
        fh.write(plain)
    with open(os.path.join(args.out, "image.h"), "w") as fh:
        fh.write(f"""// Generated by tools/pack.py from {os.path.basename(args.model)}. Do not edit.
#pragma once
#define IMG_PLAIN_BYTES   {len(plain)}u
#define IMG_ENC_BYTES     {len(enc)}u
#define IMG_TILE_BYTES    {args.tile}u
#define IMG_N_TILES       {n_tiles}u
#define IMG_VERSION       {VERSION}u
#define IMG_NONCE         {c_bytes(NONCE)}
#define IMG_K1            {c_bytes(K1)}
#define IMG_K2            {c_bytes(K2)}
""")
    print(f"{args.model}: {len(plain)} B plain, {n_tiles} tiles of {args.tile} B, image {len(enc)} B")


if __name__ == "__main__":
    main()
